"""安全写回机器人源文件的 AUTO_SEQUENCE 块

目的
====
把 kinematics.build_sequence() 生成的元组列表替换写入指定机器人 .py 文件中的
AUTO_SEQUENCE = [...] 块，同时可选更新 AUTO_RAMP_MS 整数常量。

安全策略
========
1. 备份：写入前把原文件复制为 .bak（覆盖上一次备份）。
2. 锚行 + 括号计数定位：找到 `AUTO_SEQUENCE = [` 开头的行，
   然后逐字符计 `[` +1 / `]` -1，深度归零时即找到结束行。
   跳过 # 注释和引号字符串中的方括号（见 _strip_strings_and_comments）。
3. 原子写入：先写 .tmp，`ast.parse()` 通过后用 `os.replace()` 覆盖原文件。
4. 落盘校验：覆盖后再 parse 一次，失败则从 .bak 回滚。

upsert_int_constant
-------------------
用于就地修改 `AUTO_RAMP_MS = <int>` 这行。
若文件里没有此行则自动插在 AUTO_SEQUENCE 上方。
只处理单行整数赋值；不支持多行表达式。

支持多底盘
==========
write_auto_sequence 的 robot_file 参数默认为 config.ROBOT_FILE（omni3），
main_window.py 在调用时会根据当前 ChassisProfile 传入正确路径。

注意
====
- 标定导出时传 ramp_ms=0，禁用插值，使测量更准确。
- AUTO_SEQUENCE 块必须在文件里唯一（查找第一个匹配）。
- .bak 文件每次被覆盖，不保留历史，需要更多版本控制请用 git。

API
===
  find_auto_sequence_range(text) -> (start_line, end_line)   # 0-based
  upsert_int_constant(text, name, value) -> str
  format_sequence_block(sequence, source_name, mode,
                        cm_per_s_at_p50, auto_power) -> str
  write_auto_sequence(sequence, robot_file=ROBOT_FILE, source_name,
                      mode, cm_per_s_at_p50, auto_power,
                      ramp_ms=None) -> (backup_path, True)
"""
import ast
import os
import re
import shutil
from datetime import datetime
from pathlib import Path

from .config import ROBOT_FILE

_ANCHOR_RE = re.compile(r"^\s*AUTO_SEQUENCE\s*=\s*\[")
_CONST_LINE_RE = re.compile(r"^\s*([A-Z_][A-Z0-9_]*)\s*=")


def _strip_strings_and_comments(line):
    """简化：把字符串/注释段替换为同长度空格，避免影响括号计数

    机器人代码里不会出现奇怪的字符串，只处理 # 注释和单/双引号字符串即可。
    """
    out = list(line)
    i = 0
    n = len(out)
    while i < n:
        ch = out[i]
        if ch == "#":
            for j in range(i, n):
                out[j] = " "
            break
        if ch in ("'", '"'):
            quote = ch
            triple = (i + 2 < n and out[i + 1] == quote and out[i + 2] == quote)
            if triple:
                end = quote * 3
                k = i + 3
                while k < n - 2 and "".join(out[k:k + 3]) != end:
                    out[k] = " "
                    k += 1
                # 简化处理，单行内匹配不到三引号也无所谓
                i = k + 3
                continue
            j = i + 1
            while j < n and out[j] != quote:
                if out[j] == "\\" and j + 1 < n:
                    out[j] = " "
                    out[j + 1] = " "
                    j += 2
                    continue
                out[j] = " "
                j += 1
            out[i] = " "
            if j < n:
                out[j] = " "
            i = j + 1
            continue
        i += 1
    return "".join(out)


def find_auto_sequence_range(text):
    """返回 AUTO_SEQUENCE = [...] 块的 (起始行号, 结束行号) — 0-based 包含两端"""
    lines = text.splitlines(keepends=True)
    start = None
    for idx, line in enumerate(lines):
        if _ANCHOR_RE.match(line):
            start = idx
            break
    if start is None:
        raise ValueError("未在文件中找到 AUTO_SEQUENCE = [ 锚行")

    depth = 0
    for idx in range(start, len(lines)):
        stripped = _strip_strings_and_comments(lines[idx])
        for ch in stripped:
            if ch == "[":
                depth += 1
            elif ch == "]":
                depth -= 1
                if depth == 0:
                    return start, idx
    raise ValueError("AUTO_SEQUENCE 块的结束 ] 未找到（括号不匹配？）")


def upsert_int_constant(text, name, value):
    """在文件里就地修改 `NAME = <int>` 这一行；若不存在则插入到 AUTO_SEQUENCE 上方

    返回新文本。匹配第一处 `^\\s*NAME\\s*=`；只支持单行整数赋值。
    """
    lines = text.splitlines(keepends=True)
    name_re = re.compile(r"^(\s*)" + re.escape(name) + r"\s*=\s*[^\n]*(\r?\n)?$")
    for idx, line in enumerate(lines):
        m = name_re.match(line)
        if m:
            indent = m.group(1)
            ending = m.group(2) or "\n"
            lines[idx] = "%s%s = %d%s" % (indent, name, int(value), ending)
            return "".join(lines)
    # 不存在 → 插到 AUTO_SEQUENCE 上方一行
    start, _ = find_auto_sequence_range(text)
    inject = "%s = %d  # auto-injected by trajectory_planner\n" % (name, int(value))
    lines.insert(start, inject)
    return "".join(lines)


def format_sequence_block(sequence, source_name="(manual)", mode="translation",
                          cm_per_s_at_p50=30.0, auto_power=50):
    """生成新的 AUTO_SEQUENCE = [...] 文本块（保留尾随换行）

    sequence 可包含混合元组：
      (dur, vx, vy, w)          — 标准运动步骤
      ("servo", id, angle, speed, wait_ms)  — 舵机动作
      ("delay", dur, 0, 0, 0)   — 延时
    """
    timestamp = datetime.now().strftime("%Y-%m-%d %H:%M")
    header = [
        "AUTO_SEQUENCE = [\n",
        "    # === Auto-generated by trajectory_planner on %s ===\n" % timestamp,
        "    # Source: %s\n" % source_name,
        "    # Mode: %s | cm/s@P50: %.1f | auto_power: %d\n" % (
            mode, cm_per_s_at_p50, auto_power),
    ]
    body = []
    for step in sequence:
        if isinstance(step[0], str):
            body.append("    %r,\n" % (step,))
        else:
            dur, vx, vy, w = step
            body.append("    (%5.2f, %4d, %4d, %4d),\n" % (dur, vx, vy, w))
    footer = ["]\n"]
    return "".join(header + body + footer)


def write_auto_sequence(sequence, robot_file=ROBOT_FILE, source_name="(manual)",
                        mode="translation", cm_per_s_at_p50=30.0, auto_power=50,
                        ramp_ms=None):
    """主入口：备份 → 替换 AUTO_SEQUENCE → 可选写 AUTO_RAMP_MS → 校验 → 失败回滚

    返回 (备份路径, 是否替换成功)
    """
    robot_file = Path(robot_file)
    if not robot_file.exists():
        raise FileNotFoundError("找不到机器人源文件: %s" % robot_file)

    text = robot_file.read_text(encoding="utf-8")
    start, end = find_auto_sequence_range(text)
    lines = text.splitlines(keepends=True)

    new_block = format_sequence_block(
        sequence, source_name=source_name, mode=mode,
        cm_per_s_at_p50=cm_per_s_at_p50, auto_power=auto_power,
    )

    if not new_block.endswith("\n"):
        new_block += "\n"

    new_text = "".join(lines[:start]) + new_block + "".join(lines[end + 1:])

    if ramp_ms is not None:
        new_text = upsert_int_constant(new_text, "AUTO_RAMP_MS", ramp_ms)

    backup_path = robot_file.with_suffix(robot_file.suffix + ".bak")
    shutil.copy2(robot_file, backup_path)

    tmp_path = robot_file.with_suffix(robot_file.suffix + ".tmp")
    tmp_path.write_text(new_text, encoding="utf-8")

    try:
        ast.parse(new_text)
    except SyntaxError as e:
        tmp_path.unlink(missing_ok=True)
        raise RuntimeError("生成的代码语法错误，已放弃替换: %s" % e)

    os.replace(tmp_path, robot_file)

    try:
        ast.parse(robot_file.read_text(encoding="utf-8"))
    except SyntaxError as e:
        shutil.copy2(backup_path, robot_file)
        raise RuntimeError("落盘后语法错误，已从 .bak 回滚: %s" % e)

    return backup_path, True
